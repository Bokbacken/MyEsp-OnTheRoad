#!/usr/bin/env python3
"""Embed the web UI (main/web/*) into main/web_assets.h (MyWeb::Asset table).

Each file is gzip-compressed (deterministic: mtime=0) and written as a const byte array (flash),
so the firmware serves the pages without a filesystem upload.

Usage:
  python3 tools/embed_web.py          # regenerate web_assets.h
  python3 tools/embed_web.py --check  # exit 1 if web_assets.h is out of date (CI)
"""
import gzip
import io
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "main" / "web"
OUT = ROOT / "main" / "web_assets.h"

HTML = "text/html; charset=utf-8"
# (C name, file, mime, URIs that serve it)
ASSETS = [
    ("WEB_INDEX_HTML", "index.html", HTML, ["/", "/index.html"]),
    ("WEB_SETTINGS_HTML", "settings.html", HTML, ["/settings", "/settings.html"]),
    ("WEB_DIAGNOSTICS_HTML", "diagnostics.html", HTML, ["/diag", "/diagnostics.html"]),
    ("WEB_UPDATE_HTML", "update.html", HTML, ["/update", "/update.html"]),
    ("WEB_PLAYERS_HTML", "players.html", HTML, ["/players", "/players.html"]),
    ("WEB_STYLE_CSS", "style.css", "text/css; charset=utf-8", ["/style.css"]),
]


def gz(data: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0, filename="") as f:
        f.write(data)
    return buf.getvalue()


def render() -> str:
    lines = [
        "// web_assets.h - GENERATED by tools/embed_web.py from main/web/. Do not edit by hand.",
        "#pragma once",
        "",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
        '#include "my_web.h"',
        "",
    ]
    table = []
    for name, fname, mime, uris in ASSETS:
        raw = (DATA / fname).read_bytes()
        packed = gz(raw)
        lines.append(f"// {fname}: {len(raw)} bytes -> {len(packed)} bytes gzip")
        lines.append(f"static const uint8_t {name}_DATA[] = {{")
        for i in range(0, len(packed), 20):
            chunk = ", ".join(f"0x{b:02x}" for b in packed[i:i + 20])
            lines.append(f"    {chunk},")
        lines.append("};")
        lines.append("")
        for uri in uris:
            table.append(f'    {{"{uri}", "{mime}", {name}_DATA, sizeof({name}_DATA), true}},')
    lines.append("// Registered with MyWeb::addAsset() (gzip-compressed).")
    lines.append("static const MyWeb::Asset WEB_ASSETS[] = {")
    lines.extend(table)
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print("web_assets.h is out of date - run: python3 tools/embed_web.py", file=sys.stderr)
            return 1
        print("web_assets.h is up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
