// Host harness: generates the 12 increasing-difficulty minesweeper campaign levels as .adv files
// by calling the REAL engine (World::loadMines) so the layouts are byte-identical to the campaign.
// On SD these play as fog-walk maps (minesweeper tap/flag UI only activates for the built-in path),
// so we add a guaranteed-safe EXIT cell and survivable rules, matching the shipped minfaltet file.
#include "otr_world.h"
#include <cstdio>
#include <cstring>
#include <string>

using namespace Otr;

static char glyphAt(const World &w, int x, int y)
{
    if (x == w.playerX() && y == w.playerY()) return 'S';
    if (w.tile(x, y) == Tile::TREE) return 'T';
    switch (w.rawObj(x, y)) {
        case Obj::MINE:  return 'm';
        case Obj::SUIT:  return 'u';
        case Obj::BOMB3: return 'a';
        case Obj::BOMB4: return 'z';
        default:         return '.';
    }
}

int main(int argc, char **argv)
{
    if (argc < 2) { fprintf(stderr, "usage: %s <outdir>\n", argv[0]); return 2; }
    const std::string dir = argv[1];

    for (int level = 1; level <= MINE_LEVELS; ++level) {
        World w;
        if (!w.loadMines(level)) { fprintf(stderr, "loadMines(%d) failed\n", level); return 1; }
        const int W = w.width(), H = w.height();

        // Build the glyph grid.
        std::string grid[64];
        int mineCount = 0;
        for (int y = 0; y < H; ++y) {
            grid[y].resize(W);
            for (int x = 0; x < W; ++x) {
                char g = glyphAt(w, x, y);
                if (g == 'm') ++mineCount;
                grid[y][x] = g;
            }
        }

        // Pick the farthest interior cell on the guaranteed-safe lattice (odd x OR odd y is never a
        // mine) that is currently empty grass, and make it the EXIT. Reachable from start via safe
        // rows/columns without ever stepping on a mine.
        int ex = -1, ey = -1, best = -1;
        for (int y = 1; y <= H - 2; ++y)
            for (int x = 1; x <= W - 2; ++x)
                if (((x & 1) || (y & 1)) && grid[y][x] == '.' && (x + y) > best) {
                    best = x + y; ex = x; ey = y;
                }
        if (ex < 0) { fprintf(stderr, "no safe exit cell on level %d\n", level); return 1; }
        grid[ey][ex] = 'X';

        char fname[128];
        snprintf(fname, sizeof(fname), "%s/%02d_niva%02d.adv", dir.c_str(), level, level);
        FILE *f = fopen(fname, "w");
        if (!f) { fprintf(stderr, "cannot write %s\n", fname); return 1; }

        fprintf(f, "# Generated by tools/gen_minkampanj from World::loadMines(%d) - do not hand-edit.\n", level);
        fprintf(f, "# Exact campaign layout; on SD it plays as a fog walk-to-exit map (mines leave craters).\n\n");
        fprintf(f, "@meta\n");
        fprintf(f, "id: niva%02d\n", level);
        fprintf(f, "world: 2\n");
        fprintf(f, "map_id: %d\n\n", level);

        fprintf(f, "@about\n");
        if (level == 1) {
            fprintf(f, "title.sv: Minkampanj\n");
            fprintf(f, "title.en: Mine campaign\n");
            fprintf(f, "desc.sv: Tolv banor med stigande svarighet. Vandra genom dimman, undvik minorna och na utgangen for att ga vidare till nasta niva.\n");
            fprintf(f, "desc.en: Twelve levels of rising difficulty. Walk through the fog, avoid the mines and reach the exit to advance.\n");
        } else {
            fprintf(f, "title.sv: Minkampanj - Niva %d\n", level);
            fprintf(f, "title.en: Mine campaign - Level %d\n", level);
            fprintf(f, "desc.sv: Niva %d av 12. %dx%d, %d minor.\n", level, W, H, mineCount);
            fprintf(f, "desc.en: Level %d of 12. %dx%d, %d mines.\n", level, W, H, mineCount);
        }
        fprintf(f, "author: MyEsp-OnTheRoad\n\n");

        fprintf(f, "@rules\n");
        fprintf(f, "start_energy: 8\n");
        fprintf(f, "energy_cap: 20\n");
        fprintf(f, "lives: 3\n");
        fprintf(f, "lava_damage: 3\n");
        fprintf(f, "mine_damage: 4\n");
        fprintf(f, "suit_base_steps: 3\n");
        fprintf(f, "suit_per_extra_max: 1\n");
        fprintf(f, "potion_default: 2\n");
        fprintf(f, "heart_default: 1\n");
        fprintf(f, "fog: true\n");
        fprintf(f, "carry: energy maxenergy lives suit\n\n");

        fprintf(f, "@map\n");
        for (int y = 0; y < H; ++y) fprintf(f, "%s\n", grid[y].c_str());

        fclose(f);
        printf("level %2d: %2dx%-2d  mines=%-3d  exit=(%d,%d)  -> %s\n",
               level, W, H, mineCount, ex, ey, fname);
    }
    return 0;
}
