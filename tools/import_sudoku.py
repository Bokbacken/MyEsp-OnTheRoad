#!/usr/bin/env python3
"""Generate a flash-resident Sudoku block from the pinned Sudoku Exchange bank."""

import argparse
import re
import subprocess
from pathlib import Path


SOURCE_COMMIT = "d8c8ebaee0c08c412cfba96af1923dfa61c83317"
SOURCE_FILES = ("easy.txt", "medium.txt", "hard.txt", "diabolical.txt")
DIFFICULTY_NAMES = ("EASY", "MEDIUM", "HARD", "EXTREME")
RECORD = re.compile(r"^[0-9a-f]{12} ([0-9]{81}) +([0-9]+(?:\.[0-9])?)$")


def count_solutions(puzzle):
    cells = [int(ch) for ch in puzzle]
    rows = [0] * 9
    columns = [0] * 9
    boxes = [0] * 9
    for cell, digit in enumerate(cells):
        if not digit:
            continue
        bit = 1 << digit
        row, column = divmod(cell, 9)
        box = row // 3 * 3 + column // 3
        if rows[row] & bit or columns[column] & bit or boxes[box] & bit:
            return 0
        rows[row] |= bit
        columns[column] |= bit
        boxes[box] |= bit

    def search(found):
        if found >= 2:
            return found
        best_cell = -1
        best_options = 0
        best_count = 10
        for cell, digit in enumerate(cells):
            if digit:
                continue
            row, column = divmod(cell, 9)
            box = row // 3 * 3 + column // 3
            options = 0x3FE & ~(rows[row] | columns[column] | boxes[box])
            option_count = bin(options).count("1")
            if option_count == 0:
                return found
            if option_count < best_count:
                best_cell, best_options, best_count = cell, options, option_count
                if option_count == 1:
                    break
        if best_cell < 0:
            return found + 1

        row, column = divmod(best_cell, 9)
        box = row // 3 * 3 + column // 3
        while best_options:
            bit = best_options & -best_options
            best_options ^= bit
            cells[best_cell] = bit.bit_length() - 1
            rows[row] |= bit
            columns[column] |= bit
            boxes[box] |= bit
            found = search(found)
            rows[row] ^= bit
            columns[column] ^= bit
            boxes[box] ^= bit
            cells[best_cell] = 0
            if found >= 2:
                break
        return found

    return search(0)


def load_block(source_dir, block):
    puzzles = []
    start = block * 100
    for filename in SOURCE_FILES:
        path = source_dir / filename
        lines = path.read_text(encoding="ascii").splitlines()
        selected = lines[start : start + 100]
        if len(selected) != 100:
            raise ValueError(f"{path} has fewer than {start + 100} puzzles")
        difficulty_puzzles = []
        for offset, line in enumerate(selected, start=start):
            match = RECORD.fullmatch(line)
            if not match:
                raise ValueError(f"Malformed record at {filename}:{offset + 1}")
            puzzle = match.group(1)
            if count_solutions(puzzle) != 1:
                raise ValueError(f"Puzzle is not uniquely solvable: {filename}:{offset + 1}")
            difficulty_puzzles.append(puzzle)
        puzzles.append(difficulty_puzzles)
    return puzzles


def render(puzzles, block):
    lines = [
        "#pragma once",
        "",
        "// Generated by tools/import_sudoku.py; do not edit by hand.",
        f"// Sudoku Exchange Puzzle Bank commit {SOURCE_COMMIT}, block {block}.",
        "namespace Sudoku {",
        "namespace detail {",
        "static const char kPuzzleGivens[4][100][82] = {",
    ]
    for name, difficulty_puzzles in zip(DIFFICULTY_NAMES, puzzles):
        lines.append(f"    {{ // {name}")
        lines.extend(f'        "{puzzle}",' for puzzle in difficulty_puzzles)
        lines.append("    },")
    lines.extend(("};", "}", "}", ""))
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--source-dir",
        required=True,
        type=Path,
        help="checkout of grantm/sudoku-exchange-puzzle-bank",
    )
    parser.add_argument(
        "--block",
        type=int,
        default=0,
        help="zero-based block number (each block contains 100 puzzles per difficulty)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "main" / "sudoku_puzzles.h",
    )
    args = parser.parse_args()
    if args.block < 0:
        parser.error("--block must be non-negative")
    try:
        commit = subprocess.check_output(
            ["git", "-C", str(args.source_dir), "rev-parse", "HEAD"],
            text=True,
            stderr=subprocess.DEVNULL,
        ).strip()
    except (OSError, subprocess.CalledProcessError) as error:
        parser.error(f"--source-dir must be a Git checkout at the pinned source commit ({error})")
    if commit != SOURCE_COMMIT:
        parser.error(
            f"source checkout is {commit}, expected pinned commit {SOURCE_COMMIT}"
        )
    try:
        puzzles = load_block(args.source_dir, args.block)
    except (OSError, ValueError) as error:
        parser.error(str(error))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(puzzles, args.block), encoding="ascii")
    print(f"Wrote {args.output} (block {args.block}, 400 uniquely solvable puzzles)")


if __name__ == "__main__":
    main()
